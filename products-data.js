function esc(s){ return String(s).replace(/&/g,'&amp;').replace(/</g,'&lt;').replace(/>/g,'&gt;'); }

function renderCats(){
  const g = document.getElementById('catGrid');
  if(!g) return;
  g.innerHTML = CAT_ORDER.map(k=>{
    const c = CATS[k], m = CAT_META[k];
    const models = c.series.map(s=>s.rows.map(r=>r[0])).flat().slice(0,9).join(' · ');
    return '<div class="pcard" onclick="openCat(\''+k+'\')"><img class="img" src="'+c.img+'" alt="'+esc(c.title)+'" loading="lazy"><div class="body"><h3>'+esc(c.title)+'</h3><div class="models">'+esc(models)+'</div><p class="p">'+esc(c.desc)+'</p><div class="tags">'+m.tags.map(t=>'<span class="tag">'+t+'</span>').join('')+'</div><div class="expand-hint">&#9656; Click to view all models</div></div></div>';
  }).join('');
}

function openCat(k){
  const c = CATS[k];
  if(!c) return;
  const isPsu = (k==='psu');
  document.getElementById('catTitle').innerHTML = c.title;
  document.getElementById('catBody').innerHTML = c.series.map(s=>{
    const cols = isPsu ? psuCols() : (SERIES_COLS[s.name] || defaultCols(s.rows[0].length));
    const head = cols.map(h=>'<th>'+esc(h)+'</th>').join('');
    const body = s.rows.map(r=>'<tr>'+r.map(cell=>'<td>'+esc(cell)+'</td>').join('')+'</tr>').join('');
    const sImg = s.img ? '<img class="sc-img" src="'+s.img+'" alt="'+esc(s.name)+'" loading="lazy">' : '';
    return '<div class="sub-card" onclick="toggleSub(this)"><div class="sc-top">'+sImg+'<div class="sc-body"><h4>'+esc(s.name)+'</h4><div class="sc-model">'+s.rows.length+' models</div><div class="sc-expand">&#9662; Specs</div></div></div><div class="sc-detail"><table class="spec-table"><thead><tr>'+head+'</tr></thead><tbody>'+body+'</tbody></table></div></div>';
  }).join('');
  document.getElementById('catModal').classList.add('active');
  document.body.style.overflow='hidden';
}

function closeCat(){ document.getElementById('catModal').classList.remove('active'); document.body.style.overflow=''; }
function toggleSub(el){ el.classList.toggle('expanded'); }
document.addEventListener('DOMContentLoaded', renderCats);
document.addEventListener('keydown', function(e){ if(e.key==='Escape'){ document.getElementById('catModal').classList.remove('active'); document.body.style.overflow=''; } });
